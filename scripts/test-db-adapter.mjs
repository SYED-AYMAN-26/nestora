#!/usr/bin/env node
/**
 * Database adapter conformance suite.
 *
 * Runs the SAME assertions against whichever backend DATABASE_URL selects, so
 * SQLite and PostgreSQL can be compared claim by claim:
 *
 *   node scripts/test-db-adapter.mjs                     # SQLite
 *   DATABASE_URL=postgres://… node scripts/test-db-adapter.mjs   # PostgreSQL
 *
 * Everything here is a real query against a real engine — no mocks.
 */
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BACKEND = process.env.DATABASE_URL ? "postgres" : "sqlite";

let pass = 0;
const failures = [];

function check(name, cond, detail = "") {
  if (cond) {
    pass++;
    console.log(`  ✓ ${name}`);
  } else {
    failures.push(`${name}${detail ? ` — ${detail}` : ""}`);
    console.log(`  ✗ ${name}${detail ? ` — ${detail}` : ""}`);
  }
}

/** Loads the real TypeScript adapter (no mocks, no reimplementation). */
async function loadDb() {
  const { register } = await import("esbuild-register/dist/node.js");
  register();
  const { createRequire } = await import("node:module");
  const req = createRequire(import.meta.url);
  return req(path.join(ROOT, "src/lib/db.ts"));
}

async function main() {
  // The adapter imports `pg`/`better-sqlite3` lazily, so it needs a real Node
  // process. Run this file with the compiled loader instead:
  console.log(`\n${"=".repeat(66)}\nDatabase adapter conformance — backend: ${BACKEND}\n${"=".repeat(66)}`);

  const db = await loadDb();
  const { one, all, run, tx, toDialect, backend } = db;

  check("backend reported by the adapter", backend === BACKEND, `got ${backend}`);

  /* ------------------------------------------------ 1. placeholder rewrite */
  {
    const out = toDialect(`SELECT * FROM t WHERE a = ? AND b = ?`);
    check(
      "? placeholders become $1..$n (postgres) / unchanged (sqlite)",
      BACKEND === "sqlite" ? out.includes("?") : out.includes("$1") && out.includes("$2"),
      out
    );
    const lit = toDialect(`SELECT 'is it?' AS q, ? FROM t`);
    check(
      "? inside a string literal is NOT treated as a parameter",
      BACKEND === "sqlite" ? true : lit.includes("'is it?'") && lit.includes("$1") && !lit.includes("$2"),
      lit
    );
    const cmt = toDialect(`SELECT ? /* what? no */ FROM t -- really? no\n`);
    check(
      "? inside comments is NOT treated as a parameter",
      BACKEND === "sqlite" ? true : (cmt.match(/\$\d/g) || []).length === 1,
      cmt.replace(/\n/g, "\\n")
    );
    const ident = toDialect(`SELECT "we?ird" AS c, ?`);
    check(
      "? inside a quoted identifier is NOT treated as a parameter",
      BACKEND === "sqlite" ? true : (ident.match(/\$\d/g) || []).length === 1
    );
  }

  /* ------------------------------------------------ 2. dialect translations */
  {
    const d = toDialect(`SELECT * FROM b WHERE created_at >= datetime('now','-60 days')`);
    check(
      "datetime('now','-60 days') translated",
      BACKEND === "sqlite" ? d.includes("datetime('now','-60 days')") : d.includes("interval '-60 days'"),
      d
    );
    const t = toDialect(`SELECT * FROM b WHERE start_date <= date('now','+1 day')`);
    check(
      "date('now','+1 day') translated",
      BACKEND === "sqlite" ? t.includes("date('now','+1 day')") : t.includes("interval '+1 day'"),
      t
    );
    const i = toDialect(`SELECT 1 FROM t WHERE instr(a, ?) > 0`);
    check(
      "instr() translated to position()",
      BACKEND === "sqlite" ? i.includes("instr(") : i.includes("position(") && !i.includes("instr("),
      i
    );
  }

  /* ------------------------------------------------ 3. live queries */
  // A probe table of our own: the suite must not depend on application tables.
  // (Created with the same DDL on both engines so the comparison is honest.)
  await run(`CREATE TABLE IF NOT EXISTS conformance_probe (
    id INTEGER ${BACKEND === "postgres" ? "GENERATED BY DEFAULT AS IDENTITY" : ""} PRIMARY KEY,
    tag TEXT NOT NULL UNIQUE,
    n INTEGER NOT NULL DEFAULT 0,
    txt TEXT
  )`);

  const tag = `adp_${Date.now().toString(36)}`;

  // clean slate for this run
  await run(`DELETE FROM conformance_probe WHERE tag = ?`, tag);

  const ins = await run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, tag, 1, "one");
  check("INSERT returns a usable id", Number(ins.lastInsertRowid) > 0, `lastInsertRowid=${ins.lastInsertRowid}`);

  const row = await one(`SELECT * FROM conformance_probe WHERE tag = ?`, tag);
  check("one() returns the inserted row", Boolean(row) && Number(row.n) === 1);
  check("numeric column round-trips as a number", typeof row?.n === "number", `typeof n = ${typeof row?.n}`);

  const id = Number(ins.lastInsertRowid);
  await run(`UPDATE conformance_probe SET n = ? WHERE id = ?`, 2, id);
  const after = await one(`SELECT n FROM conformance_probe WHERE id = ?`, id);
  check("UPDATE reports through a subsequent read", Number(after.n) === 2);

  const cnt = await one(`SELECT COUNT(*) AS c FROM conformance_probe WHERE tag = ?`, tag);
  check("COUNT(*) is a number, not a string", typeof cnt.c === "number" && Number(cnt.c) === 1, `typeof c = ${typeof cnt.c}`);

  const sum = await one(`SELECT COALESCE(SUM(n),0) AS s FROM conformance_probe WHERE tag = ?`, tag);
  check("SUM()/COALESCE is a number", typeof sum.s === "number");

  // ? that is a plain literal must not shift parameters
  const litQ = await one(`SELECT ? AS v, 'has?mark' AS w`, "bound");
  check(
    "literal '?' does not shift bound parameters",
    litQ.v === "bound" && litQ.w === "has?mark",
    JSON.stringify(litQ)
  );

  // string containing a quote
  const quote = await one(`SELECT ? AS v`, "O'Brien ? $1");
  check("parameter with quotes and ?-chars round-trips", quote.v === "O'Brien ? $1", quote.v);

  /* ------------------------------------------------ 4. unique constraints */
  await run(`DELETE FROM conformance_probe WHERE tag = ?`, tag);
  await run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, tag, 1, "u");
  let uniqueErr = null;
  try {
    await run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, tag, 2, "u");
  } catch (e) {
    uniqueErr = e;
  }
  check("UNIQUE constraint is enforced", Boolean(uniqueErr), uniqueErr ? "" : "duplicate accepted");

  // ON CONFLICT DO UPDATE (upsert used by rate limiter / track / booking_usage).
  // NOTE: the self-reference must be table-qualified. `SET n = n + 1` is legal on
  // SQLite but "column reference is ambiguous" on PostgreSQL — the application
  // query was written as table.col for exactly this reason.
  await run(
    `INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)
     ON CONFLICT(tag) DO UPDATE SET n = conformance_probe.n + 1`,
    tag, 10, "u"
  );
  const upserted = await one(`SELECT n FROM conformance_probe WHERE tag = ?`, tag);
  check(
    "ON CONFLICT DO UPDATE with a table-qualified self-reference works (1 → 2)",
    Number(upserted.n) === 2,
    `n = ${upserted?.n}`
  );

  /* ------------------------------------------------ 5. transactions */
  {
    const before = (await one(`SELECT COUNT(*) AS c FROM conformance_probe WHERE tag = ?`, tag)).c;
    let threw = null;
    try {
      await tx(async () => {
        await run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, tag, 1, "tx");
        await run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, tag, 1, "tx"); // unique violation
      });
    } catch (e) {
      threw = e;
    }
    const afterCount = (await one(`SELECT COUNT(*) AS c FROM conformance_probe WHERE tag = ?`, tag)).c;
    check("failed transaction rolls back (error surfaced)", Boolean(threw));
    check("failed transaction left no rows behind", Number(afterCount) === Number(before), `${before} → ${afterCount}`);
  }

  {
    const okTx = await tx(async () => {
      await run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, `${tag}_c`, 1, "commit");
      return "done";
    });
    const committed = await one(`SELECT COUNT(*) AS c FROM conformance_probe WHERE tag = ?`, `${tag}_c`);
    check("successful transaction commits and returns its value", okTx === "done" && Number(committed.c) === 1);
  }

  // nested transaction must be rejected, not silently merged
  let nestedErr = null;
  try {
    await tx(async () => {
      await tx(async () => undefined);
    });
  } catch (e) {
    nestedErr = e;
  }
  check("nested tx() is explicitly rejected", nestedErr && /nested/i.test(nestedErr.message), nestedErr?.message);

  /* ------------------------------------------------ 6. concurrency */
  {
    // 12 concurrent writers outside a transaction, then 8 concurrent transactions
    const N = 12;
    await run(`DELETE FROM conformance_probe WHERE tag LIKE ?`, `${tag}_par%`);
    await Promise.all(
      Array.from({ length: N }, (_, i) =>
        run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, `${tag}_par_${i}`, i, `p${i}`)
      )
    );
    const c1 = await one(`SELECT COUNT(*) AS c FROM conformance_probe WHERE tag LIKE ?`, `${tag}_par%`);
    check(`${N} concurrent inserts all land`, Number(c1.c) === N, `count = ${c1.c}`);

    const txN = 8;
    await Promise.all(
      Array.from({ length: txN }, (_, i) =>
        tx(async () => {
          await run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, `${tag}_tx_${i}`, i, `t${i}`);
          await new Promise((r) => setTimeout(r, 5));
          await run(`UPDATE conformance_probe SET n = n + 100 WHERE tag = ?`, `${tag}_tx_${i}`);
        })
      )
    );
    const c2 = await all(`SELECT n FROM conformance_probe WHERE tag LIKE ? ORDER BY n`, `${tag}_tx\_%`);
    const allBumped = c2.length === txN && c2.every((r) => Number(r.n) >= 100);
    check(
      `${txN} concurrent transactions each read their own writes`,
      allBumped,
      JSON.stringify(c2.map((r) => r.n))
    );
  }

  /* ------------------------------------------------- 6b. LIKE case sensitivity */
  {
    // SQLite LIKE is case-insensitive; PostgreSQL's is not. The adapter rewrites
    // the operator to ILIKE, and this asserts the resulting BEHAVIOUR is the same
    // on both engines rather than asserting the rewrite happened.
    await run(`DELETE FROM conformance_probe WHERE tag LIKE ?`, `%_case_%`);
    await run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, `${tag}_case_canon`, 1, "Canon EOS 90D");
    for (const [pattern, expect] of [
      ["%canon%", 1], ["%CANON%", 1], ["%CaNoN%", 1], ["%90d%", 1], ["%nikon%", 0],
    ]) {
      const r = await one(`SELECT COUNT(*) AS c FROM conformance_probe WHERE txt LIKE ?`, pattern);
      check(`LIKE '${pattern}' matches the same rows on every engine`, Number(r.c) === expect, `expected ${expect}, got ${r.c}`);
    }
    // A literal containing the word LIKE must not be rewritten.
    const lit = await one(`SELECT ? AS v`, "x LIKE y");
    check("the word LIKE inside a parameter is untouched", lit.v === "x LIKE y");
    const litSql = await one(`SELECT 'a LIKE b' AS v, ? AS w`, "z");
    check("the word LIKE inside a SQL literal is untouched", litSql.v === "a LIKE b" && litSql.w === "z");
  }

  /* ------------------------------ 6c. date/time semantics, controlled data */
  {
    // Same known timestamps are written to both engines, so any difference in the
    // result is a dialect difference and not a difference in the data.
    await run(`DELETE FROM conformance_probe WHERE tag LIKE ?`, `${tag}_dt%`);
    const now = Date.now();
    const iso = (offsetDays) => new Date(now + offsetDays * 864e5).toISOString();
    const day = (offsetDays) => new Date(now + offsetDays * 864e5).toISOString().slice(0, 10);
    const rowsByTag = [
      [`${tag}_dt_past`, iso(-200)],   // ~7 months ago
      [`${tag}_dt_recent`, iso(-10)],
      [`${tag}_dt_today`, iso(0)],
      [`${tag}_dt_future`, iso(3)],
    ];
    for (const [tg, ts] of rowsByTag) {
      await run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, tg, 0, ts);
    }

    const last6 = await one(
      `SELECT COUNT(*) AS c FROM conformance_probe WHERE txt >= datetime('now','-6 months') AND tag LIKE ?`,
      `${tag}_dt%`
    );
    check(
      "datetime('now','-6 months') excludes exactly the row older than 6 months",
      Number(last6.c) === 3,
      `got ${last6.c}`
    );

    const todayOrLater = await one(
      `SELECT COUNT(*) AS c FROM conformance_probe WHERE txt >= date('now') AND tag LIKE ?`,
      `${tag}_dt%`
    );
    check("date('now') comparison keeps today and future rows", Number(todayOrLater.c) === 2, `got ${todayOrLater.c}`);

    const soon = await one(
      `SELECT COUNT(*) AS c FROM conformance_probe WHERE substr(txt,1,10) <= date('now','+1 day') AND tag LIKE ?`,
      `${tag}_dt%`
    );
    check("date('now','+1 day') arithmetic is inclusive", Number(soon.c) === 3, `got ${soon.c}`);

    // ISO strings with a 'T' and a 'Z' must order correctly against the
    // "YYYY-MM-DD HH:MM:SS" form the schema default produces.
    const mixedFormat = await one(
      `SELECT COUNT(*) AS c FROM conformance_probe WHERE txt >= ? AND tag LIKE ?`,
      "2000-01-01 00:00:00", `${tag}_dt%`
    );
    check("ISO 'T…Z' values compare correctly with 'YYYY-MM-DD HH:MM:SS' bounds", Number(mixedFormat.c) === 4, `got ${mixedFormat.c}`);

    // substr(...,1,7) month grouping used by the impact dashboard
    const months = await all(
      `SELECT substr(txt,1,7) AS month, COUNT(*) AS c FROM conformance_probe WHERE tag LIKE ? GROUP BY month ORDER BY month`,
      `${tag}_dt%`
    );
    const total = months.reduce((a, r) => a + Number(r.c), 0);
    check(
      "substr(col,1,7) month grouping works",
      total === 4 && months.every((r) => /^\d{4}-\d{2}$/.test(String(r.month))),
      JSON.stringify(months.map((r) => `${r.month}:${r.c}`))
    );

    // the day-bucket expression must equal a plain JS date slice
    const bucket = await one(`SELECT substr(?,1,10) AS d`, iso(0));
    const expectedDay = day(0);
    check(
      "substr(?,1,10) produces the same YYYY-MM-DD as the application",
      bucket.d === expectedDay,
      `${bucket.d} vs ${expectedDay}`
    );

    await run(`DELETE FROM conformance_probe WHERE tag LIKE ?`, `${tag}_dt%`);
  }

  /* --------------------------------- 7. concurrent cold-start initialisation */
  {
    // A serverless cold start can receive N requests at once. If init() were not
    // shared, each would open its own pool / file handle. Simulated here by
    // clearing the module-level state and firing 25 queries simultaneously.
    globalThis.__rentlinkDb = undefined;
    const started = Date.now();
    const many = await Promise.all(
      Array.from({ length: 25 }, (_, i) => one(`SELECT ? AS i`, i))
    );
    const allOk = many.every((r, i) => Number(r.i) === i);
    const state = globalThis.__rentlinkDb;
    check(
      "25 simultaneous first queries all succeed after a cold start",
      allOk,
      allOk ? `${Date.now() - started}ms` : JSON.stringify(many.slice(0, 3))
    );
    check(
      "cold start opens exactly one connection pool / file handle",
      Boolean(state) && Boolean(state.pool || state.sqlite),
      state ? Object.keys(state).filter((k) => k === "pool" || k === "sqlite").join(",") : "no state"
    );

    // and a concurrent write burst against the fresh instance
    const writes = await Promise.all(
      Array.from({ length: 10 }, (_, i) =>
        run(`INSERT INTO conformance_probe (tag, n, txt) VALUES (?,?,?)`, `${tag}_cold_${i}`, i, "cold")
      )
    );
    check("10 simultaneous writes on a fresh instance all report success", writes.every((w) => w.changes === 1));
    await run(`DELETE FROM conformance_probe WHERE tag LIKE ?`, `${tag}_cold%`);
  }

  /* ------------------------------------------------ 8. cleanup */
  await run(`DELETE FROM conformance_probe WHERE tag LIKE ?`, `${tag}%`);
  const left = await one(`SELECT COUNT(*) AS c FROM conformance_probe WHERE tag LIKE ?`, `${tag}%`);
  check("probe rows cleaned up", Number(left.c) === 0);

  console.log(`\n${BACKEND}: ${pass} passed, ${failures.length} failed`);
  if (failures.length) {
    console.log("\nFAILURES:");
    for (const f of failures) console.log(`  - ${f}`);
    process.exitCode = 1;
  }
  if (db.closeDb) await db.closeDb();
}

main().catch((e) => {
  console.error("\nADAPTER SUITE CRASHED:", e);
  process.exit(1);
});
